<h2 id="understand">النطق المتصل / Connected Speech</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 المتحدثين الأصليين نادرًا ما بينطقوا كل كلمة "كاملة ومنفصلة" زي ما بنتعلمها في الكتب. الكلمات بتتلزق ببعض (Linking)، وبعض الكلمات بتتقصر (Reductions) زي "going to" اللي بتتنطق "gonna"، و"want to" اللي بتبقى "wanna". ده مش "كلام غلط" — دي طريقة النطق الطبيعية في المحادثة العادية.</div>
    <div class="en">🇬🇧 Native speakers rarely pronounce every word "complete and separate" the way we learn from books. Words link together, and some words get reduced — "going to" becomes "gonna," and "want to" becomes "wanna." This isn't "incorrect speech" — it's the natural pronunciation of ordinary conversation.</div>
</div>
<div class="output-box">Reductions شائعة / Common reductions:
  going to  →  gonna       "I'm gonna finish this today."
  want to   →  wanna       "Do you wanna join the call?"
  got to    →  gotta       "I gotta go now."
  kind of   →  kinda       "It's kinda difficult."

Linking (ربط الكلمات) / Linking words together:
  "an apple"     يتنطق كأنه   "a-napple"    (الحرف الساكن بيتلزق بالحركة اللي بعده)
  "turn it off"  يتنطق كأنه   "tur-ni-toff"
  "check it out" يتنطق كأنه   "che-ki-taut"</div>
<div class="bi-block">
    <div class="ar">🇪🇬 مهم توضيح: "gonna" و"wanna" مناسبة في الكلام العادي غير الرسمي، لكن في الكتابة الرسمية (إيميل شغل، تقرير) لازم تكتب "going to" و"want to" كاملة.</div>
    <div class="en">🇬🇧 Important clarification: "gonna" and "wanna" are fine in casual speech, but in formal writing (a work email, a report) you should always write "going to" and "want to" in full.</div>
</div>

<h2>تقنية الظل: Shadowing</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 Shadowing تقنية بسيطة وقوية جدًا: تسمع جملة قصيرة من متحدث أصلي (فيديو، بودكاست)، توقف، وتكررها بنفس الإيقاع والتنغيم بالظبط — مش بس نفس الكلمات، لكن نفس "موسيقى" الجملة (فين الصوت بيعلى، فين بيقصر، فين بيتوقف).</div>
    <div class="en">🇬🇧 Shadowing is a simple, very powerful technique: you hear a short sentence from a native speaker (video, podcast), pause, and repeat it with the exact same rhythm and intonation — not just the same words, but the same "music" of the sentence (where the pitch rises, where it shortens, where it pauses).</div>
</div>
<div class="output-box">خطوات Shadowing عملية / Practical Shadowing steps:
  1. اختار فيديو قصير (30 ثانية - دقيقة) بسرعة عادية، مش بطيئة صناعيًا.
  2. اسمع جملة واحدة، وقف الفيديو.
  3. كررها بصوت عالي، بنفس الإيقاع بالظبط، حتى لو محسيتش إنك فاهم كل كلمة.
  4. شغّل الجملة تاني وقارن نفسك بيها.
  5. كرر العملية 10-15 دقيقة يوميًا — الاستمرارية أهم من المدة الطويلة.</div>
<div class="bi-block">
    <div class="ar">🇪🇬 أكبر عائق نفسي بيمنع الناس من التحدث هو الخوف من الغلط. الحقيقة: المتحدث الأصلي بيقدّر إنك بتحاول تتكلم لغته، وبيركز على المعنى مش على كل خطأ نحوي صغير. ابدأ بجمل قصيرة وبسيطة، واقبل إن الغلط جزء طبيعي وضروري من التعلم — كل جملة تتكلمها بثقة، حتى لو فيها خطأ، بتقربك خطوة من الطلاقة.</div>
    <div class="en">🇬🇧 The biggest psychological barrier stopping people from speaking is fear of mistakes. The truth: native speakers appreciate that you're trying to speak their language, and they focus on meaning, not every small grammatical slip. Start with short, simple sentences, and accept that mistakes are a natural, necessary part of learning — every sentence you speak with confidence, even with an error, moves you a step closer to fluency.</div>
</div>

