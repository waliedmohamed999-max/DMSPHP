<h2 id="understand">عبارات الطوارئ الحيوية / Vital Emergency Phrases</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 في حالة طوارئ، مفيش وقت لجمل طويلة — لازم تقول اللي عايزه في أقل عدد كلمات ممكن وبأعلى وضوح. دي أهم 5 عبارات لازم تكون جاهزة في دماغك على طول من غير تفكير.</div>
    <div class="en">🇬🇧 In an emergency, there's no time for long sentences — you need to say what you mean in as few words as possible, as clearly as possible. Here are the 5 most essential phrases that should be instantly ready in your mind, no thinking required.</div>
</div>
<div class="output-box">Call an ambulance! → اتصل بالإسعاف!
I need help! → محتاج مساعدة!
Where's the nearest hospital? → فين أقرب مستشفى؟
There's a fire! → فيه حريق!
Call the police! → اتصل بالشرطة!</div>

<h2>مكالمة طوارئ حقيقية / A Realistic Emergency Call</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 لما تتصل بخط الطوارئ، هيسألك المستقبِل عن نوع الحالة، مكانك، وتفاصيل بسيطة — بهدوء وبالترتيب. اقرا المثال ده وتخيل نفسك في نفس الموقف.</div>
    <div class="en">🇬🇧 When you call an emergency line, the operator will ask you about the type of situation, your location, and a few simple details — calmly and in order. Read this example and imagine yourself in the same situation.</div>
</div>
<div class="output-box">Operator: Emergency services, what's your emergency?
Caller: There's been a car accident on Nile Street, near the bridge. A man is injured and he's not moving.
Operator: Okay, stay calm. Is he conscious? Is he breathing?
Caller: Yes, he's breathing, but he's not responding when I talk to him.
Operator: I'm sending an ambulance now. Please stay on the line and don't move him.
Caller: Okay, please hurry, we need help fast!</div>
<div class="output-box">الترجمة الكاملة / Full translation:

المستقبِل: خدمات الطوارئ، إيه حالة الطوارئ عندك؟
المتصل: حصل حادثة عربية في شارع النيل، جنب الكوبري. راجل مصاب ومش بيتحرك.
المستقبِل: طيب، خليك هادي. هو واعي؟ بيتنفس؟
المتصل: أيوه، بيتنفس، بس مش بيستجيب لما بكلمه.
المستقبِل: هبعتلك إسعاف دلوقتي. من فضلك خليك على الخط ومتحركوش.
المتصل: تمام، بسرعة من فضلك، محتاجين مساعدة بسرعة!</div>
<div class="bi-block">
    <div class="ar">🇪🇬 لاحظ: المستقبِل بيسأل أسئلة قصيرة ومباشرة (Is he conscious? Is he breathing?)، والرد المطلوب منك بسيط بردود "Yes/No" ومعلومات إضافية قليلة — متحاولش تشرح كل حاجة مرة واحدة.</div>
    <div class="en">🇬🇧 Notice: the operator asks short, direct questions (Is he conscious? Is he breathing?), and the expected response from you is simple yes/no answers with a little extra information — don't try to explain everything at once.</div>
</div>

<h2>عبارات إضافية للسلامة / More Safety Phrases</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 مش كل موقف طارئ بيحتاج إسعاف أو شرطة — أحيانًا بس محتاج تحذّر حد أو تطلب مخرج آمن.</div>
    <div class="en">🇬🇧 Not every emergency needs an ambulance or the police — sometimes you just need to warn someone or ask for a safe way out.</div>
</div>
<div class="output-box">Watch out! → احترس!
It's not safe here, we need to leave now. → مش أمان هنا، لازم نمشي دلوقتي.
Where's the emergency exit? → فين مخرج الطوارئ؟
Someone fainted, please call for help! → حد وقع مغشي عليه، اتصلوا للمساعدة!
I'm allergic to this — I need a doctor immediately. → عندي حساسية من ده — محتاج دكتور فورًا.</div>

