<h2 id="understand">العمل الحر مقابل الوظيفة الثابتة / Freelancing vs. Full-Time</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 <b>العمل الحر (Freelance):</b> بتشتغل مع عملاء مختلفين بمشاريع منفصلة، عندك حرية أكبر في المواعيد والأسعار، لكن مسؤول عن جلب عملاء جدد باستمرار ومفيش دخل ثابت مضمون. <b>الوظيفة الثابتة (In-house / Agency):</b> بتشتغل جوه شركة أو وكالة تصميم، دخل ثابت شهري وفريق تتعلم منه، لكن حريتك في اختيار المشاريع أقل وبتلتزم بمواعيد ثابتة. مفيش خيار "أفضل" مطلقًا — يعتمد على شخصيتك واستقرارك المادي المطلوب.</div>
    <div class="en">🇬🇧 <b>Freelance:</b> you work with different clients on separate projects, more freedom over schedule and pricing, but you're responsible for constantly finding new clients and there's no guaranteed steady income. <b>Full-time (in-house / agency):</b> you work inside a company or design agency, steady monthly income and a team to learn from, but less freedom in choosing projects and fixed schedules. Neither is objectively "better" — it depends on your personality and how much financial stability you need.</div>
</div>

<h2>يوم في حياة مصمم / A Day in the Life</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 نفس مسمى "مصمم جرافيك" بيعني يوم شغل مختلف تمامًا حسب المسار: <b>Freelance:</b> بتفتح يومك برد على رسائل عملاء محتملين وعروض أسعار، بعدين شوية ساعات تصميم فعلي لـ2-3 عملاء مختلفين في نفس اليوم، وبعدين وقت إداري (فواتير، متابعة مواعيد تسليم، البحث عن عملاء جدد على منصات زي Behance أو مواقع فريلانس) — الجدول مرن لكن عليك عبء إداري كبير كل يوم. <b>وكالة (Agency):</b> مواعيد ثابتة، اجتماع صباحي سريع مع الفريق (Stand-up)، مهام موزّعة عليك من مدير إبداعي (Creative Director)، بتشتغل على أكتر من براند عميل في نفس الوقت مع جولات مراجعة وتعديل متكررة — التواصل مع العميل نفسه غالبًا مش شغلتك، ده شغل مدير الحسابات. <b>داخل شركة (In-house):</b> بتشتغل لبراند واحد بس طول الوقت، فبتبقى خبير جدًا في دليل هويته، مهامك يومية ومتكررة (بوست سوشيال ميديا، بانر إيميل، مواد لحدث)، أقل تنوع لكن استقرار وتواصل مباشر مع فريق التسويق والمنتج.</div>
    <div class="en">🇬🇧 The same job title "graphic designer" means a completely different workday depending on the path: <b>Freelance:</b> your day opens replying to prospective clients and quotes, then a few hours of actual design work for 2-3 different clients the same day, then admin time (invoicing, tracking deadlines, hunting new clients on platforms like Behance or freelance sites) — flexible schedule but a heavy daily admin burden. <b>Agency:</b> fixed hours, a quick morning team stand-up, tasks assigned by a Creative Director, working on more than one client brand at once with repeated review-and-revision rounds — talking to the client directly is usually not your job, that's the account manager's. <b>In-house:</b> you work for one brand only, all the time, so you become deeply expert in its guideline, your tasks are daily and repetitive (a social post, an email banner, event materials), less variety but stability and direct contact with the marketing and product teams.</div>
</div>

