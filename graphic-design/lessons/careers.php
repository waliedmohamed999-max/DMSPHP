<h2>تسعير أول مشروع Freelance / Pricing Your First Freelance Project</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 أشهر غلطة عند المبتدئين في التسعير: يقول رقم عشوائي ("500 جنيه كده؟") من غير حساب فعلي، فيلاقي نفسه خسران وقته. الطريقة الصح: احسب الساعات المتوقعة، اضرب في سعر ساعتك، وضيف هامش أمان.</div>
    <div class="en">🇬🇧 The most common beginner pricing mistake: throwing out a random number ("maybe 500 pounds?") with no real calculation, then ending up losing time and money. The right method: estimate the hours, multiply by your hourly rate, and add a safety margin.</div>
</div>
<div class="recap-box">
    <h3>🗺️ سيناريو واقعي: شعار + بطاقة عمل لمخبز صغير / Realistic Scenario: Logo + Business Card for a Small Bakery</h3>
    <ul>
        <li><b>بحث وفهم البراند:</b> ساعتين (2h) — تفهم المخبز، منافسينه، وجمهوره.</li>
        <li><b>3 مقترحات شعار أولية:</b> 4 ساعات (4h).</li>
        <li><b>جولتين تعديل بعد فيدباك العميل:</b> 3 ساعات (3h).</li>
        <li><b>تصميم بطاقة العمل بناءً على الشعار النهائي:</b> ساعتين (2h).</li>
        <li><b>الإجمالي:</b> 11 ساعة عمل فعلي.</li>
        <li><b>سعر الساعة لمبتدئ (مثال):</b> 150 جنيه/ساعة → 11 × 150 = 1,650 جنيه.</li>
        <li><b>هامش أمان (تعديلات غير متوقعة، وقت تواصل):</b> +20% تقريبًا → السعر النهائي المعروض: حوالي 2,000 جنيه، مع تحديد "جولتين تعديل مجانًا بس" في العرض.</li>
    </ul>
</div>
<div class="bi-block">
    <div class="ar">🇪🇬 لاحظ التفصيلة الأهم: العرض بيحدد "جولتين تعديل بس" بوضوح من الأول. من غير الحد ده، عميل ممكن يطلب تعديل رقم 15 بنفس السعر، وتلاقي نفسك اشتغلت 30 ساعة بسعر 11 ساعة. حط الحد في العرض المكتوب دايمًا، وأي تعديل زيادة عن الحد يتحسب بسعر إضافي منفصل.</div>
    <div class="en">🇬🇧 Notice the most important detail: the quote clearly caps it at "two revision rounds only" from the start. Without that cap, a client could ask for revision number 15 at the same price, and you'd end up doing 30 hours of work for an 11-hour price. Always state the cap in the written quote, and any revision beyond it gets billed separately.</div>
</div>

<h2>بناء Portfolio من غير عملاء حقيقيين / Building a Portfolio Without Real Clients</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 أشهر عقبة عند المبتدئين: "محدش هيوظفني من غير Portfolio، ومعنديش Portfolio لأن محدش وظفني لسه." الحل: مشاريع "إعادة تصميم" (Redesign) — يعني تاخد بوستر أو منشور سوشيال ميديا حقيقي موجود بالفعل لبراند معروف، وتعيد تصميمه بشكل أفضل، وتكتب بالتفصيل قراراتك: ليه غيّرت الألوان؟ ليه استخدمت خط تاني؟ إيه المشكلة في التصميم الأصلي اللي حليتها؟ المشاريع دي بتوريك للعميل المحتمل مش بس "شكل حلو" لكن طريقة تفكيرك كمصمم.</div>
    <div class="en">🇬🇧 The most common beginner obstacle: "nobody will hire me without a portfolio, and I have no portfolio because nobody's hired me yet." The solution: redesign projects — take a real existing poster or social media post from a known brand and redesign it better, then write in detail about your decisions: why did you change the colors? Why a different font? What problem in the original did you solve? These projects show a potential client not just "a nice look" but your thinking process as a designer.</div>
</div>

<div class="exercise-box">
    <h3>✍️ تمرين عملي / Hands-on Exercise</h3>
    <div class="ar">🇪🇬 دوّر على بوستر أو منشور سوشيال ميديا حقيقي (لأي براند تعرفه) فيه مشكلة تصميمية واضحة (تباين ضعيف، محاذاة مبعثرة، خطوط كتير، أو ألوان متعارضة مع رسالة البراند — ارجع لمراحل التصميم اللي فاتت لو محتاج تفتكر). اكتب: (1) إيه المشكلة بالضبط، (2) إيه اللي هتغيّره تحديدًا، (3) ليه التغيير ده هيخلي الرسالة توصل أوضح. الوصف ده نفسه ممكن يبقى نواة أول قطعة في الـ Portfolio بتاعك.</div>
    <div class="en">🇬🇧 Find a real poster or social media post (from any brand you know) with a clear design problem (weak contrast, scattered alignment, too many fonts, or colors clashing with the brand's message — revisit earlier stages if you need a refresher). Write: (1) what exactly is the problem, (2) what specifically you'd change, (3) why that change would make the message land more clearly. This write-up itself can become the seed of your first portfolio piece.</div>
</div>

