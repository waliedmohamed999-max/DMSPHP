<h2 id="challenge">🛠️ Challenge</h2>
<div class="challenge-box">
    <h3>🛠️ سعّر مشروعك الأول / Price Your First Project</h3>
    <div class="ar">🇪🇬 عميل طلب منك حزمة 10 بوستات سوشيال ميديا لإطلاق منتج جديد. قدّر: (1) عدد الساعات المتوقعة لكل بوست (بحث + تصميم + تعديل)، (2) سعر ساعتك الحالي بناءً على خبرتك، (3) السعر الإجمالي بعد هامش الأمان، (4) عدد جولات التعديل اللي هتحددها في العرض. اكتب الأرقام والحسبة بالتفصيل، مش رقم نهائي عشوائي.</div>
    <div class="en">🇬🇧 A client asks you for a package of 10 social media posts for a new product launch. Estimate: (1) expected hours per post (research + design + revision), (2) your current hourly rate based on your experience, (3) the total price after the safety margin, (4) how many revision rounds you'll cap the quote at. Write out the numbers and the math in detail, not a random final figure.</div>
</div>

