    <div class="en">🇬🇧 Notice the fundamental difference: SEO is calm work with slow results, social media is reactive work at a fast daily pace, and paid ads is work built on real-time numbers with higher pressure since budget is moving every minute. If you like stability and long-term planning, SEO or content strategy fits better. If you like fast interaction and daily creativity, social media fits better. If you like numbers and fast decisions under pressure, paid ads or analytics fits better.</div>
</div>

<h2>عمل حر مقابل وكالة مقابل داخلي / Freelancing vs Agency vs In-house</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 <b>العمل الحر (Freelancing):</b> تشتغل مع عملاء متعددين بنفسك، حرية كاملة في المواعيد لكن مسؤولية كاملة عن جلب العملاء والتفاوض على السعر — مناسب لمن يحب التنوع والاستقلالية لكنه يتحمل عدم استقرار الدخل في البداية. <b>الوكالة (Agency):</b> تشتغل موظف في شركة بتقدم خدمات تسويق لعملاء متعددين — بتتعلم بسرعة من التنوع والزملاء الأكبر خبرة، لكن الضغط والمواعيد النهائية عادة أعلى. <b>الداخلي (In-house):</b> تشتغل جوه شركة واحدة بتسوّق لمنتجها هي بس — بتتعمق جدًا في منتج وجمهور واحد، استقرار أعلى، لكن تنوع تجربتك أقل من الوكالة.</div>
    <div class="en">🇬🇧 <b>Freelancing:</b> you work with multiple clients on your own, full schedule freedom but full responsibility for finding clients and negotiating rates — suits someone who likes variety and independence but can handle unstable income early on. <b>Agency:</b> you're an employee at a company that provides marketing services to multiple clients — you learn fast from variety and more experienced coworkers, but pressure and deadlines are usually higher. <b>In-house:</b> you work inside one company marketing only its own product — you go deep on one product and audience, with more stability but less variety than an agency.</div>
</div>

<h2>بناء Portfolio بدون عملاء سابقين / Building a Portfolio With No Prior Clients</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 أكبر عائق بيواجه المبتدئين هو "محدش هيوظفني من غير خبرة، ومحدش هيديني خبرة من غير ما اتوظف". الحل العملي: اعمل حملة وهمية (mock campaign) كاملة لمشروع شخصي حقيقي أو فكرة خيالية، ووثّق العملية بالكامل زي ما لو كان عميل حقيقي.</div>
    <div class="en">🇬🇧 The biggest obstacle beginners face is "no one will hire me without experience, and no one gives me experience without hiring me." The practical solution: run a full mock campaign on a real personal project or an invented idea, and document the entire process as if it were a real client.</div>
</div>

<h2>قالب Portfolio جاهز للاستخدام / A Ready-to-Use Portfolio Template</h2>
<div class="bi-block">
    <div class="ar">🇪🇬 مش محتاج تصميم معقد أو موقع احترافي مكلف — صفحة Notion بسيطة، عرض Google Slides، أو حتى موقع شخصي من صفحة واحدة كفاية تمامًا في البداية. المهم هو المحتوى مش الشكل. القالب المقترح:</div>
</div>
<div class="output-box">📋 قالب Portfolio تسويقي للمبتدئين:

1. نبذة سريعة (About)
   جملتين: مين انت، وإيه المهارات اللي عندك (اربطها بمراحل هذا المسار: SEO، محتوى، سوشيال، إيميل، إعلانات، تحليلات).

2. من 2 إلى 3 دراسات حالة (Case Studies) — كل واحدة بصيغة:
   المشكلة (Problem): إيه كان التحدي؟ (مثال: "صفحة انستجرام شخصية معدل تفاعلها كان ضعيف جدًا")
   الفعل (Action): إيه اللي عملته بالظبط؟ (مثال: "طبقت جدول محتوى أسبوعي لمدة شهر، مع تنويع الشكل بين Reels وCarousel")
   النتيجة (Result) بالأرقام: إيه اللي تغيّر فعليًا؟ (مثال: "التفاعل الحقيقي (تعليقات + مشاركات) زاد من 12 لـ 47 أسبوعيًا خلال شهر")

3. قائمة الأدوات والمهارات (Tools & Skills)
   مثال: Google Analytics، أساسيات SEO، تخطيط محتوى، كتابة إعلانية بإطار AIDA.

4. شهادات أو توصيات (لو موجودة، ولو مفيش متسيبش الفراغ فاضي — احذف القسم بدل ما تتركه فاضي)

5. طريقة تواصل واضحة (Contact/CTA)
   إيميل أو رابط مباشر، وجملة دعوة بسيطة زي "عايز تناقش مشروعك؟ راسلني."</div>
<div class="bi-block">
    <div class="ar">🇪🇬 القسم الأهم في القالب ده هو دراسات الحالة بصيغة (مشكلة → فعل → نتيجة) — ده بالظبط الفرق بين "أنا عارف تسويق" و"أنا عملت كذا وحققت كذا". صاحب العمل أو العميل المحتمل مش بيدور على قايمة مهارات نظرية، هو بيدور على دليل إنك تقدر تحقق نتيجة فعلية، حتى لو كانت النتيجة دي على مشروعك الشخصي مش عميل حقيقي بيدفعلك.</div>
    <div class="en">🇬🇧 The most important part of this template is the case studies in (Problem → Action → Result) format — that's exactly the difference between "I know marketing" and "I did X and achieved Y." An employer or potential client isn't looking for a list of theoretical skills, they're looking for proof you can produce a real outcome, even if that outcome was on your own personal project rather than a paying client.</div>
</div>

<div class="exercise-box">
    <h3>✍️ تمرين عملي / Hands-on Exercise</h3>
    <div class="ar">🇪🇬 صمم خطة "حملة وهمية" كاملة لمشروع شخصي أو فكرة خيالية، تجمع فيها 3 مهارات على الأقل اتعلمتها في المسار ده (مثلًا: عنوان صفحة SEO + جدول محتوى سوشيال لأسبوع + إعلان بإطار AIDA). اكتب خطة توثيق واضحة: إيه هتقيسه (KPI محدد) قبل وبعد، عشان تقدر تعرضها كـ case study حقيقي في مقابلة شغل أو لعميل محتمل.</div>
    <div class="en">🇬🇧 Design a full "mock campaign" plan for a personal project or invented idea, combining at least 3 skills learned in this track (e.g. an SEO page title + a week-long social content calendar + an AIDA-framework ad). Write a clear documentation plan: what you'd measure (a specific KPI) before and after, so you can present it as a real case study in a job interview or to a potential client.</div>
</div>

